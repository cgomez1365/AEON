/**
 * Desktop icon for a cloned AEON install.
 *
 * CEO, 2026-09-13: the operator should open AEON from an icon on the Desktop,
 * not by finding launch.command / LAUNCH.bat inside a cloned folder. The
 * launchers stay — the icon runs them — so the console window, the first-run
 * wizard and "close the window to stop AEON" all behave exactly as before.
 *
 *   macOS    ~/Desktop/AEON.app — a bundle whose only job is
 *            `open -a Terminal <install>/launch.command`
 *   Windows  <Desktop>\AEON.lnk — LAUNCH.bat, this install's AEON.ico
 *   other    skipped, and says so
 *
 * Every open is also an index: server.js runs an incremental Second Brain scan
 * shortly after each boot, so the icon needs no indexing logic of its own.
 *
 * Rules, and why:
 *   - Portable/USB media writes nothing to the host (BO-USB). No icon there.
 *   - AEON_NO_DESKTOP_ICON=1 opts out. An icon the operator deleted stays
 *     deleted; `node launch.js --desktop-icon` (force) brings it back.
 *   - A moved install repoints its own icon; an AEON.app / AEON.lnk this code
 *     did not make is never modified.
 *   - The Desktop is asked of the OS (Finder / .NET), never built from a home
 *     directory — scan:paths forbids that, and on Windows the Desktop is often
 *     redirected into OneDrive, where %USERPROFILE%\Desktop is the wrong folder.
 *   - Paths are data: the bundle script single-quotes the install path, and
 *     PowerShell receives every path through environment variables, so nothing
 *     a folder name contains can execute.
 *   - The macOS icon is assembled from the committed per-size brand PNGs (the
 *     compact cut at 16/32, the full mark above), never resampled from one
 *     master — the brand rule, and the reason `npm run brand:icons` is the only
 *     writer of those PNGs.
 *
 * State lives inside the install at data/desktop-shortcut.json (git-ignored),
 * so it travels with the operator's data through a re-clone.
 */
'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');

const BUNDLE_ID = 'io.brokengear.aeon.launcher';
const LINK_MARK = 'AEON — generated by launch.js';
const STATE_REL = path.join('data', 'desktop-shortcut.json');

// iconutil file name → committed brand PNG size it is copied from.
const ICONSET = [
  ['icon_16x16.png', 16], ['icon_16x16@2x.png', 32],
  ['icon_32x32.png', 32], ['icon_32x32@2x.png', 64],
  ['icon_128x128.png', 128], ['icon_128x128@2x.png', 256],
  ['icon_256x256.png', 256], ['icon_256x256@2x.png', 512],
  ['icon_512x512.png', 512], ['icon_512x512@2x.png', 1024],
];

function defaultRun(cmd, args = [], opts = {}) {
  const r = spawnSync(cmd, args, { encoding: 'utf8', timeout: 60000, windowsHide: true, ...opts });
  if (r.error) return { status: -1, stdout: '', stderr: r.error.message };
  return { status: r.status, stdout: r.stdout || '', stderr: r.stderr || '' };
}

/** Ask the OS where the Desktop is. null when it cannot say. */
function resolveDesktopDir({ platform, run = defaultRun } = {}) {
  let r;
  if (platform === 'darwin') {
    r = run('osascript', ['-e', 'POSIX path of (path to desktop folder)']);
  } else if (platform === 'win32') {
    r = run('powershell', ['-NoProfile', '-NonInteractive', '-Command', "[Environment]::GetFolderPath('Desktop')"]);
  } else {
    return null;
  }
  if (!r || r.status !== 0) return null;
  const dir = String(r.stdout || '').trim().replace(/[\\/]+$/, '');
  return dir || null;
}

function readState(root) {
  try { return JSON.parse(fs.readFileSync(path.join(root, STATE_REL), 'utf8')); } catch { return null; }
}

function writeState(root, state) {
  const file = path.join(root, STATE_REL);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, JSON.stringify(state, null, 2) + '\n');
}

// ── macOS ────────────────────────────────────────────────────────────────────

/** POSIX single-quote: the only character needing care inside '…' is ' itself. */
function shQuote(s) {
  return `'${String(s).replace(/'/g, `'\\''`)}'`;
}

function macExecutable(root) {
  return [
    '#!/bin/bash',
    '# Generated by AEON (launch.js). Opens this install\'s launcher in Terminal so',
    '# the console stays visible; closing that window shuts AEON down.',
    `AEON_ROOT=${shQuote(root)}`,
    'exec open -a Terminal "$AEON_ROOT/launch.command"',
    '',
  ].join('\n');
}

function macInfoPlist() {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>AEON</string>
  <key>CFBundleDisplayName</key><string>AEON</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundleExecutable</key><string>AEON</string>
  <key>CFBundleIconFile</key><string>AEON</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>3.0</string>
  <key>LSMinimumSystemVersion</key><string>10.13</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
`;
}

/** Build Resources/AEON.icns. Returns a warning string, or undefined on success. */
function buildIcns({ root, resourcesDir, run }) {
  const brand = path.join(root, 'public', 'brand', 'aeon-mark');
  const missing = [...new Set(ICONSET.map(([, px]) => px))]
    .filter(px => !fs.existsSync(path.join(brand, `aeon-icon-${px}.png`)));
  if (missing.length) {
    return `brand icon PNGs missing (${missing.join(', ')} px) — AEON.app will show a generic icon`;
  }
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'aeon-iconset-'));
  const iconset = path.join(tmp, 'AEON.iconset');
  try {
    fs.mkdirSync(iconset);
    for (const [name, px] of ICONSET) fs.copyFileSync(path.join(brand, `aeon-icon-${px}.png`), path.join(iconset, name));
    const out = path.join(resourcesDir, 'AEON.icns');
    const r = run('iconutil', ['-c', 'icns', iconset, '-o', out]);
    if (!r || r.status !== 0 || !fs.existsSync(out)) {
      return `icon build failed (${String((r && r.stderr) || 'iconutil did not run').trim()}) — AEON.app still opens AEON, with a generic icon`;
    }
    return undefined;
  } finally {
    try { fs.rmSync(tmp, { recursive: true, force: true }); } catch { /* temp only */ }
  }
}

function writeMacBundle({ app, root, run }) {
  const contents = path.join(app, 'Contents');
  const resources = path.join(contents, 'Resources');
  fs.mkdirSync(path.join(contents, 'MacOS'), { recursive: true });
  fs.mkdirSync(resources, { recursive: true });
  fs.writeFileSync(path.join(contents, 'Info.plist'), macInfoPlist());
  const exe = path.join(contents, 'MacOS', 'AEON');
  fs.writeFileSync(exe, macExecutable(root));
  fs.chmodSync(exe, 0o755);
  const warning = buildIcns({ root, resourcesDir: resources, run });
  // Finder caches bundle icons by modification time.
  try { const now = new Date(); fs.utimesSync(app, now, now); } catch { /* cosmetic */ }
  return warning;
}

function ensureMac({ root, desktopDir, run, state, force }) {
  const app = path.join(desktopDir, 'AEON.app');
  const plistFile = path.join(app, 'Contents', 'Info.plist');
  const exeFile = path.join(app, 'Contents', 'MacOS', 'AEON');

  if (fs.existsSync(app)) {
    let plist = '';
    try { plist = fs.readFileSync(plistFile, 'utf8'); } catch { /* not a bundle we made */ }
    if (!plist.includes(`<string>${BUNDLE_ID}</string>`)) return { status: 'skipped', reason: 'foreign', path: app };
    let current = '';
    try { current = fs.readFileSync(exeFile, 'utf8'); } catch { /* rewrite below */ }
    const hasIcon = fs.existsSync(path.join(app, 'Contents', 'Resources', 'AEON.icns'));
    if (current === macExecutable(root) && hasIcon) return { status: 'present', path: app };
    const warning = writeMacBundle({ app, root, run });
    return { status: 'updated', path: app, ...(warning ? { warning } : {}) };
  }

  if (!force && state && state.path === app) return { status: 'skipped', reason: 'removed-by-user', path: app };
  const warning = writeMacBundle({ app, root, run });
  return { status: 'created', path: app, ...(warning ? { warning } : {}) };
}

// ── Windows ──────────────────────────────────────────────────────────────────

// Static text: every path arrives through $env:, so no folder name is ever
// parsed as PowerShell. One statement per line — `-Command -` reads stdin
// line by line.
const PS_SHORTCUT = [
  "$ErrorActionPreference = 'Stop'",
  '$shell = New-Object -ComObject WScript.Shell',
  '$link = $env:AEON_SC_LINK',
  '$existed = Test-Path -LiteralPath $link',
  '$s = $shell.CreateShortcut($link)',
  "$icon = $env:AEON_SC_ICON + ',0'",
  "if ($existed -and $s.TargetPath -eq $env:AEON_SC_TARGET -and $s.WorkingDirectory -eq $env:AEON_SC_WORKDIR -and $s.IconLocation -eq $icon) { 'present'; exit 0 }",
  "if ($existed -and $s.Description -ne $env:AEON_SC_MARK) { 'foreign'; exit 0 }",
  '$s.TargetPath = $env:AEON_SC_TARGET',
  '$s.WorkingDirectory = $env:AEON_SC_WORKDIR',
  '$s.IconLocation = $icon',
  '$s.Description = $env:AEON_SC_MARK',
  '$s.WindowStyle = 1',
  '$s.Save()',
  "if ($existed) { 'updated' } else { 'created' }",
  '',
].join('\n');

function ensureWindows({ root, desktopDir, run, state, force, env }) {
  const link = path.join(desktopDir, 'AEON.lnk');
  if (!fs.existsSync(link) && !force && state && state.path === link) {
    return { status: 'skipped', reason: 'removed-by-user', path: link };
  }
  const r = run('powershell', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', '-'], {
    input: PS_SHORTCUT,
    env: {
      ...process.env, ...env,
      AEON_SC_LINK: link,
      AEON_SC_TARGET: path.join(root, 'LAUNCH.bat'),
      AEON_SC_WORKDIR: root,
      AEON_SC_ICON: path.join(root, 'AEON.ico'),
      AEON_SC_MARK: LINK_MARK,
    },
  });
  if (!r || r.status !== 0) {
    return { status: 'failed', reason: String((r && (r.stderr || r.stdout)) || 'PowerShell did not run').trim(), path: link };
  }
  const said = String(r.stdout || '').split(/\r?\n/).map(s => s.trim()).filter(Boolean).pop();
  if (said === 'foreign') return { status: 'skipped', reason: 'foreign', path: link };
  if (['created', 'updated', 'present'].includes(said)) return { status: said, path: link };
  return { status: 'failed', reason: `unexpected PowerShell output: ${said || '(none)'}`, path: link };
}

// ── entry ────────────────────────────────────────────────────────────────────

/**
 * @param {{ root: string, platform: string, env?: object, desktopDir?: string,
 *           force?: boolean, run?: Function }} opts
 * @returns {{ status: 'created'|'updated'|'present'|'skipped'|'failed',
 *             reason?: string, path?: string, warning?: string }}
 */
function ensureDesktopShortcut(opts = {}) {
  const { root, platform, env = {}, force = false, run = defaultRun } = opts;
  if (!root || !path.isAbsolute(root)) throw new Error('ensureDesktopShortcut: root must be an absolute path');

  if (env.AEON_PORTABLE === 'true') return { status: 'skipped', reason: 'portable' };
  if (env.AEON_NO_DESKTOP_ICON === '1' || env.AEON_NO_DESKTOP_ICON === 'true') return { status: 'skipped', reason: 'opted-out' };
  if (platform !== 'darwin' && platform !== 'win32') return { status: 'skipped', reason: 'unsupported-platform' };

  const desktopDir = opts.desktopDir || resolveDesktopDir({ platform, run });
  if (!desktopDir || !fs.existsSync(desktopDir)) return { status: 'skipped', reason: 'no-desktop' };

  const state = readState(root);
  const result = platform === 'darwin'
    ? ensureMac({ root, desktopDir, run, state, force })
    : ensureWindows({ root, desktopDir, run, state, force, env });

  if (['created', 'updated', 'present'].includes(result.status)) {
    try {
      writeState(root, { path: result.path, root, platform, at: new Date().toISOString() });
    } catch { /* the icon works; only its memory of itself failed */ }
  }
  return result;
}

module.exports = { ensureDesktopShortcut, resolveDesktopDir, BUNDLE_ID };
