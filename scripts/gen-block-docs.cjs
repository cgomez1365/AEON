#!/usr/bin/env node
// Generates docs/BLOCKS.md from block manifests.
// Run: node scripts/gen-block-docs.cjs   (part of `npm run build`)
//
// The hand-maintained version listed hr_arsenal, outreach and scheduler — all
// deleted — and a status probe file that no longer exists, while omitting every
// block added since. docs/ sits outside every scanner, so nothing ever caught
// it. Generating beats validating: a generated doc cannot go stale.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const blocksDir = path.join(ROOT, 'src', 'blocks');
const outFile = path.join(ROOT, 'docs', 'BLOCKS.md');

function apiFiles(dir) {
  const out = [];
  const walk = (d, prefix = '') => {
    if (!fs.existsSync(d)) return;
    for (const e of fs.readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      if (e.name.startsWith('_')) continue;
      if (e.isDirectory()) walk(path.join(d, e.name), `${prefix}${e.name}/`);
      else if (/\.(js|cjs)$/.test(e.name)) out.push(prefix + e.name);
    }
  };
  walk(dir);
  return out;
}

const rows = [];
for (const folder of fs.readdirSync(blocksDir).sort()) {
  if (folder.startsWith('_')) continue;
  const manifestPath = path.join(blocksDir, folder, 'block.manifest.json');
  if (!fs.existsSync(manifestPath)) continue;

  let m;
  try { m = JSON.parse(fs.readFileSync(manifestPath, 'utf8')); }
  catch { continue; }

  const perms = m?.contract?.permissions || {};
  const capabilities = Object.entries(perms)
    .filter(([, v]) => v && v !== 'none')
    .map(([k, v]) => (v === true ? k : `${k}:${v}`))
    .sort();

  rows.push({
    id: m.id || folder,
    label: m.nav?.label || m.label || folder,
    route: m.nav?.route || m.route || '—',
    memory: m?.contract?.memory?.mode || 'none',
    cloud: m?.contract?.targets?.vercel === false ? 'desktop only' : 'desktop + cloud',
    capabilities,
    api: apiFiles(path.join(blocksDir, folder, 'api')),
  });
}

const body = rows.map(r => `### ${r.label}

- **ID:** \`${r.id}\`
- **Route:** \`${r.route}\`
- **Targets:** ${r.cloud}
- **Memory mode:** \`${r.memory}\`
- **Declared capabilities:** ${r.capabilities.length ? r.capabilities.map(c => `\`${c}\``).join(', ') : '_none_'}
- **API files:** ${r.api.length ? r.api.map(f => `\`${f}\``).join(', ') : '_none_'}
`).join('\n');

const output = `# AEON Block Registry

<!-- AUTO-GENERATED by scripts/gen-block-docs.cjs — do not edit by hand.
     Regenerate with \`npm run prep:docs\` (also runs as part of \`npm run build\`). -->

${rows.length} installed blocks, read from each \`block.manifest.json\`.

"Declared capabilities" are the permissions the manifest asks for. They are
enforced by \`createScopedDeps\` in both desktop and cloud mounting — a block
receives only what it declares.

${body}`;

fs.writeFileSync(outFile, output, 'utf8');
console.log(`[gen-block-docs] Wrote ${rows.length} blocks to docs/BLOCKS.md`);
