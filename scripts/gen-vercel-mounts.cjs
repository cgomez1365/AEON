#!/usr/bin/env node
// Generates api/index.js from block manifests + on-disk api/ files.
// Run: node scripts/gen-vercel-mounts.cjs
// Wired into: "vercel-build" in package.json

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const blocksDir = path.join(ROOT, 'src', 'blocks');
const outFile = path.join(ROOT, 'api', 'index.js');

function collectApiFiles() {
  const entries = [];
  for (const folder of fs.readdirSync(blocksDir).sort()) {
    if (folder.startsWith('_')) continue;
    const manifestPath = path.join(blocksDir, folder, 'block.manifest.json');
    if (!fs.existsSync(manifestPath)) continue;

    const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
    const vercel = manifest?.contract?.targets?.vercel;
    if (vercel === false) continue;

    const apiDir = path.join(blocksDir, folder, 'api');
    if (!fs.existsSync(apiDir)) continue;

    collectDir(apiDir, folder, entries);
  }
  return entries;
}

function collectDir(dir, folder, entries) {
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    if (item.name.startsWith('_')) continue;
    const full = path.join(dir, item.name);
    if (item.isDirectory()) {
      collectDir(full, folder, entries);
    } else if (item.name.endsWith('.js') || item.name.endsWith('.cjs')) {
      const rel = path.relative(path.join(ROOT, 'api'), full).replace(/\\/g, '/');
      entries.push({ folder, rel });
    }
  }
}

const files = collectApiFiles();

const lines = files.map(f => `    '${f.rel}',`).join('\n');

const output = `// AUTO-GENERATED by scripts/gen-vercel-mounts.cjs — do not edit by hand
// Vercel NFT requires static require paths; this file is regenerated at build time.

global.mountStaticBlocks = function(app, deps) {
  const mounts = [
${lines}
  ];
  // Mirror blockHost.cjs signature detection: factory (deps)=>router files
  // must have their RETURNED router mounted — calling them as (app, deps)
  // silently discards the router (found 2026-07-16: /api/research/* 404 on web).
  for (const m of mounts) {
    try {
      const factory = require(m);
      if (typeof factory !== 'function') continue;
      if (typeof factory.use === 'function' && Array.isArray(factory.stack)) {
        app.use('/api', factory);                 // exported a bare router
      } else if (factory.length === 1) {
        const result = factory(deps);             // factory pattern
        if (result && typeof result.use === 'function') app.use('/api', result);
      } else {
        factory(app, deps);                       // plugin pattern
      }
    } catch(e) { console.error('[VERCEL] Static mount error (' + m + '):', e.message); }
  }
};

module.exports = require('../server.cjs');
`;

fs.writeFileSync(outFile, output, 'utf8');
console.log(`[gen-vercel-mounts] Wrote ${files.length} API mounts to api/index.js`);
